import type { CSSProperties, ReactNode } from 'react'
import { cn } from '@/lib/cn'
import { photos, type PhotoName } from '@/data/media'

/**
 * Photography.
 *
 * WHY THERE ARE PHOTOGRAPHS HERE AT ALL
 * The source documents specify illustration for Phase 1 and photography "once
 * available" in Phase 2, on the grounds that showing a campus that is not open
 * would be an overclaim. That reasoning is about *false* photographs — pictures
 * that imply an LBS KidZ classroom exists. It is not an argument against
 * showing what early childhood actually looks like.
 *
 * So photography is used, and the overclaim is prevented by what the site says
 * rather than by a notice about the pictures:
 *   - No photograph is captioned, framed or implied as an LBS KidZ campus,
 *     classroom, child, parent or educator. Nothing says "our".
 *   - The Campuses page shows materials, never a room with children in it.
 *   - Campuses, Gallery, Educators and Testimonials keep their honest "not yet"
 *     states, which is where a reader is actually told what does not exist yet.
 *   - The Shastri family pages take no stock photography at all.
 * Provenance for every file is kept in image-credits.json, which is a licence
 * ledger for the team and not something a parent is shown.
 * See docs/decisions-and-todos.md item C-04.
 *
 * HOW IT RENDERS
 * One <picture> per image: AVIF, then WebP, then JPEG, each with a srcset built
 * from the widths actually present on disk (see src/data/media.ts, generated by
 * scripts/build-image-manifest.mjs). Intrinsic width and height are always
 * emitted so nothing shifts while the file arrives, and the average colour of
 * the image is painted underneath so the space is never blank white.
 */

const IMAGE_BASE = '/images'

const sourceSet = (name: PhotoName, extension: 'avif' | 'webp' | 'jpg') => {
  const meta = photos[name]
  return meta.widths
    .map((width) => {
      // The largest render is stored unsuffixed by the sourcing toolkit.
      const file = width === meta.width ? `${name}.${extension}` : `${name}-${width}w.${extension}`
      return `${IMAGE_BASE}/${file} ${width}w`
    })
    .join(', ')
}

export type PhotoProps = {
  name: PhotoName
  /** Overrides the manifest's alt text when the same image says something
   *  different in a new context. Pass "" only for genuinely decorative use. */
  alt?: string
  className?: string
  /** Applied to the <img> itself; use for object-position tuning. */
  imgClassName?: string
  /**
   * The `sizes` attribute. Getting this wrong is the single most expensive
   * mistake available here, so every caller states it.
   */
  sizes: string
  /** The LCP image. Loads eagerly at high priority and is never lazy. */
  priority?: boolean
  /** CSS aspect-ratio for the frame, e.g. "3/4". Defaults to the file's own. */
  ratio?: string
  /**
   * Take height from the container instead of from an aspect ratio. Used by
   * the page header, whose height is fixed at 40vh and must not shift because
   * one route's photograph happens to be a different shape from another's.
   */
  fill?: boolean
  /**
   * Aspect ratio expressed as Tailwind classes rather than an inline style, so
   * it can change per breakpoint. A single `ratio` cannot do that, and a
   * cinematic band that reads well at 1440px collapses to a 167px sliver on a
   * phone. Takes precedence over `ratio`.
   */
  ratioClassName?: string
  /** object-position, for when the subject is not centred. */
  focus?: string
  style?: CSSProperties
}

export function Photo({
  name,
  alt,
  className,
  imgClassName,
  sizes,
  priority = false,
  ratio,
  fill = false,
  ratioClassName,
  focus,
  style,
}: PhotoProps) {
  const meta = photos[name]
  const aspect = ratio ?? `${meta.width} / ${meta.height}`
  const inlineAspect = fill || ratioClassName ? undefined : aspect

  return (
    <span
      className={cn(
        'relative block overflow-hidden',
        fill && 'size-full',
        ratioClassName,
        className,
      )}
      style={{ aspectRatio: inlineAspect, backgroundColor: meta.tint, ...style }}
    >
      <picture>
        <source type="image/avif" srcSet={sourceSet(name, 'avif')} sizes={sizes} />
        <source type="image/webp" srcSet={sourceSet(name, 'webp')} sizes={sizes} />
        <img
          src={`${IMAGE_BASE}/${name}.jpg`}
          srcSet={sourceSet(name, 'jpg')}
          sizes={sizes}
          alt={alt ?? meta.alt}
          width={meta.width}
          height={meta.height}
          loading={priority ? 'eager' : 'lazy'}
          decoding={priority ? 'sync' : 'async'}
          fetchPriority={priority ? 'high' : 'auto'}
          draggable={false}
          className={cn(
            'absolute inset-0 size-full object-cover',
            focus ? undefined : 'object-center',
            imgClassName,
          )}
          style={focus ? { objectPosition: focus } : undefined}
        />
      </picture>
    </span>
  )
}

